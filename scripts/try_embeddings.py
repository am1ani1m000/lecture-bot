PAIRS = [
    # (категория, текст A, текст B, ожидание)
    ("синонимы", "Кошка спит на диване", "Котёнок дремлет на софе", "похожи"),
    ("синонимы", "Студент сдал экзамен", "Учащийся успешно прошёл испытание", "похожи"),
    ("синонимы", "Машина едет быстро", "Автомобиль мчится с большой скоростью", "похожи"),
    ("перифраз", "Python это язык программирования", "Питон является языком для написания программ", "похожи"),
    ("перифраз", "Вода кипит при 100 градусах", "Температура кипения воды составляет 100 °C", "похожи"),
    ("перифраз", "Сила равна массе на ускорение", "Чтобы найти силу, умножь массу на ускорение", "похожи"),
    ("разные темы", "Кошка спит на диване", "Курс доллара вырос на два рубля", "разные"),
    ("разные темы", "Python это язык программирования", "Вчера я ходил в магазин за хлебом", "разные"),
    ("разные темы", "Вода кипит при 100 градусах", "Футбольная команда выиграла матч", "разные"),
    ("разные темы", "Студент сдал экзамен", "Рецепт борща с говядиной", "разные"),
    ("отрицание", "Я люблю кошек", "Я не люблю кошек", "разные"),
    ("отрицание", "Лекция была полезной", "Лекция была бесполезной", "разные"),
    ("отрицание", "Файл можно удалять", "Файл удалять нельзя", "разные"),
    ("числа", "Скорость равна 5 м/с", "Скорость равна 50 м/с", "разные"),
    ("числа", "Лекция длится 90 минут", "Лекция длится 20 минут", "разные"),
    ("числа", "В группе 25 студентов", "В группе 250 студентов", "разные"),
    ("омонимы", "Банк выдал кредит", "Мы сидели на берегу у банка реки", "разные"),
    ("омонимы", "Лук нужно нарезать для супа", "Он натянул лук и выпустил стрелу", "разные"),
    ("омонимы", "Ключ от квартиры остался дома", "Из-под земли бьёт холодный ключ", "разные"),
    ("два языка", "Кошка спит на диване", "The cat is sleeping on the sofa", "похожи"),
    ("два языка", "Курс доллара вырос", "The dollar exchange rate went up", "похожи"),
    ("вопрос и ответ", "Что такое эмбеддинг?", "Эмбеддинг это превращение текста в набор чисел", "похожи"),
    ("вопрос и ответ", "Что такое эмбеддинг?", "Рецепт борща включает свёклу и капусту", "разные"),
    ("вопрос и ответ", "Когда сдавать курсовую?", "Срок сдачи курсовой работы 15 декабря", "похожи"),
    ("вопрос и ответ", "Когда сдавать курсовую?", "Кошка спит на диване", "разные"),
]

model = SentenceTransformer(MODEL_NAME)
print("длина вектора:", len(model.encode(["тест"])[0]))

scored = []
for category, a, b, expected in PAIRS:
    va, vb = model.encode([a, b])
    scored.append((category, a, b, expected, util.cos_sim(va, vb).item()))


def accuracy(threshold):
    """Доля пар, где решение по порогу совпало с ожиданием."""
    hits = sum((s >= threshold) == (e == "похожи") for _, _, _, e, s in scored)
    return hits / len(scored)


best = max(THRESHOLDS, key=accuracy)
print("порог -> доля верных")
for t in THRESHOLDS:
    print(f"{t:.1f} -> {accuracy(t):.0%}")
print("лучший порог:", best)

by_category = defaultdict(list)
rows = []
for category, a, b, expected, score in scored:
    ok = (score >= best) == (expected == "похожи")
    by_category[category].append(ok)
    rows.append([category, a, b, expected, round(score, 3), "верно" if ok else "ошибка"])

print("\nпо категориям (верно / всего):")
for category, oks in by_category.items():
    print(f"{category}: {sum(oks)} / {len(oks)}")

with open("pairs_results.csv", "w", newline="", encoding="utf-8-sig") as f:
    writer = csv.writer(f)
    writer.writerow(["category", "sentence_a", "sentence_b", "expected", "score", "verdict"])
    writer.writerows(rows)